import type { AllergenTag, DietTag, FoodSourceRef } from './types';

/**
 * Food schema v2 — nutrition metadata for every FOOD_DB entry (P0-4).
 *
 * FOOD_DB itself (macros.ts + indian-foods.ts) carries only
 * calories/protein/carbs/fat. This overlay adds, per DB key:
 *
 *  - fiberG      dietary fiber per 100 g, on the SAME basis as the entry's
 *                macros (cooked where the entry is cooked, dry where dry).
 *  - dietTag     one explicit classification per entry:
 *                'vegan' | 'veg' | 'egg' | 'non-veg'.
 *  - allergenTags subset of ALLERGEN_TAGS (controlled vocabulary).
 *  - sourceRef   where the entry's values come from.
 *
 * Derivation rules (documented so the data can be re-derived and audited):
 *  - sourceRef: the original curated Indian overlay values
 *    (INDIAN_FOOD_VALUES) are IFCT tabulations and read 'IFCT 2017';
 *    dish additions from the P0-1 bridge work are recipe estimates and
 *    read 'estimated' even when they live in the same overlay file. Supplements and
 *    branded packaged products are 'label'. Plain whole foods whose values
 *    track standard references are 'USDA FDC'. Everything else — prepared
 *    dishes and composites whose numbers are recipe estimates — is
 *    'estimated'. No value in this file is presented as measured when it
 *    is an estimate.
 *  - fiberG: IFCT values for Indian entries, USDA FDC values for reference
 *    foods, recipe-composition estimates for composite dishes (which are
 *    exactly the entries whose sourceRef is 'estimated').
 *  - dietTag reflects the standard preparation of the dish — the DB's own
 *    recipe assumption in INDIAN_FOOD_META where one exists. Ambiguous
 *    prepared dishes are tagged 'veg' rather than 'vegan' (e.g. a tadka
 *    that is commonly ghee). Raw plant ingredients and dishes whose
 *    standard recipe is oil-based and dairy-free are 'vegan'.
 *  - allergenTags lists allergens that are INGREDIENTS of the standard
 *    recipe (not cross-contact): dairy foods and dishes built on
 *    milk/curd/paneer/butter/cream are 'milk'; South-Indian tadka dishes
 *    where mustard-seed tempering is definitional carry 'mustard';
 *    peanut is tagged where peanuts are an ingredient (lemon rice,
 *    sabudana khichdi, Maggi tastemaker), never for frying oil alone.
 *
 * Completeness is enforced by tests/food-schema-v2.test.ts: every FOOD_DB
 * key must have exactly one entry here, and vice versa.
 */

export interface FoodNutritionMeta {
  /** Dietary fiber in grams per 100 g (same basis as the entry's macros). */
  fiberG: number;
  dietTag: DietTag;
  allergenTags: AllergenTag[];
  sourceRef: FoodSourceRef;
}


/**
 * Resolve a classifier label to its bridge entry. Lookup is by exact
 * label (case/whitespace-normalized) — deliberately no fuzzy fallback:
 * an unknown label resolves to 'none' so the caller uses the
 * cloud/manual path instead of a guessed price.
 */
export function resolveScanLabel(label: string): ScanBridgeEntry {
  if (!label) return { dbKey: null, matchType: 'none' };
  return SCAN_BRIDGE[label.toLowerCase().trim()] ?? { dbKey: null, matchType: 'none' };
}
